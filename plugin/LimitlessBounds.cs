using System;
using System.Security.Cryptography;
using System.Text;

namespace CompetitiveRounds
{
    /// <summary>
    /// Ask 16(a) section 2 (D2): the clamp table and its rule, kept free of
    /// Unity, Photon and BepInEx so the harness runs it (suite `limitbounds`).
    ///
    /// The rule, one for every field: a limitless game keeps each field within
    /// what a normal game already reaches. That is K picks of the strongest
    /// shipped card in each direction, from the player's base, and at least x8
    /// either way. A field a shipped card zeroes keeps 0 as its floor; a field
    /// whose base is 0 gets [0, 8]. A count is capped at its base plus K times
    /// the largest single-card addend, and at least its base plus K. Bullets
    /// per trigger stay within the most K picks reach, and bursts give way
    /// first. The numbers below are generated by the census tool from the
    /// game's own assets (tools/limitless-census/gen_bounds.py); they are
    /// never typed. K and the table are Sid's (D2).
    ///
    /// The clamps act only in a limitless game, which lane 2's record defines.
    /// This file holds the table and the rule; lane 2 calls them after every
    /// card apply under its record. The table is part of the feature's
    /// advertised version (change 7): Version carries the protocol number and
    /// a digest of the table, so two seats with different tables never share
    /// a continuation.
    /// </summary>
    internal static class LimitlessBounds
    {
        internal const int Protocol = 1;
        internal const int K = 5;
        internal const int BulletsPerTrigger = 81;

        internal struct Range
        {
            internal readonly string Field;
            internal readonly float Base, Lo, Hi;

            internal Range(string field, float baseValue, float lo, float hi)
            {
                Field = field;
                Base = baseValue;
                Lo = lo;
                Hi = hi;
            }
        }

        internal struct Cap
        {
            internal readonly string Field;
            internal readonly int Base, Max;

            internal Cap(string field, int baseValue, int max)
            {
                Field = field;
                Base = baseValue;
                Max = max;
            }
        }

        /// <summary>The 21 multiplied fields.</summary>
        internal static readonly Range[] Ranges =
        {
            // generated by tools/limitless-census/gen_bounds.py (K = 5); never edited by hand
            new Range("GunAmmo.reloadTimeMultiplier", 1f, 0.00243000058f, 8f),
            new Range("CharacterStatModifiers.sizeMultiplier", 1f, 0.125f, 8f),
            new Range("CharacterData.maxHealth", 100f, 3.125f, 3200f),
            new Range("CharacterStatModifiers.movementSpeed", 1f, 0.125f, 8f),
            new Range("CharacterStatModifiers.jump", 1f, 0.125f, 8f),
            new Range("Gravity.gravityForce", 1000f, 125f, 8000f),
            new Range("Block.cdMultiplier", 1f, 0.125f, 8f),
            new Range("Gun.damage", 1f, 0.0009765625f, 32f),
            new Range("Gun.chargeDamageMultiplier", 1f, 0.125f, 8f),
            new Range("Gun.knockback", 1f, 0.125f, 97.65625f),
            new Range("Gun.projectileSpeed", 1f, 0.0777600184f, 525.21875f),
            new Range("Gun.projectielSimulatonSpeed", 1f, 0.125f, 32f),
            new Range("Gun.gravity", 1f, 0f, 8f),
            new Range("Gun.multiplySpread", 1f, 0.125f, 8f),
            new Range("Gun.attackSpeed", 0.300000012f, 2.92968783e-09f, 29.2968769f),
            new Range("Gun.bodyRecoil", 0f, 0f, 8f),
            new Range("Gun.speedMOnBounce", 1f, 0.03125f, 8f),
            new Range("Gun.dmgMOnBounce", 1f, 0.125f, 18.8956776f),
            new Range("Gun.bulletDamageMultiplier", 1f, 0.125f, 8f),
            new Range("Gun.damageAfterDistanceMultiplier", 1f, 0.125f, 8f),
            new Range("Gun.timeToReachFullMovementMultiplier", 0f, 0f, 8f),
        };

        /// <summary>The 8 counted fields. No shipped card adds jumps
        /// (csm.numberOfJumps is 0 on all 67 cards), so jumps cannot grow and
        /// carry no cap.</summary>
        internal static readonly Cap[] Caps =
        {
            // generated by tools/limitless-census/gen_bounds.py (K = 5); never edited by hand
            new Cap("Gun.numberOfProjectiles", 1, 21),
            new Cap("Gun.bursts", 0, 15),
            new Cap("Gun.reflects", 0, 25),
            new Cap("Gun.smartBounce", 0, 5),
            new Cap("Gun.randomBounces", 0, 5),
            new Cap("Gun.bulletPortal", 0, 5),
            new Cap("Block.additionalBlocks", 0, 5),
            new Cap("CharacterStatModifiers.respawns", 0, 5),
        };

        /// <summary>A multiplied field's clamp. NaN reads as the floor, and
        /// an infinity as its matching end.</summary>
        internal static float Clamp(Range r, float v)
        {
            if (float.IsNaN(v)) return r.Lo;
            if (v < r.Lo) return r.Lo;
            if (v > r.Hi) return r.Hi;
            return v;
        }

        /// <summary>A count's cap.</summary>
        internal static int Clamp(Cap c, int v)
        {
            return v > c.Max ? c.Max : v;
        }

        /// <summary>Bursts give way first: the bursts value that keeps
        /// projectiles x max(1, bursts) within BulletsPerTrigger. Projectiles
        /// are capped first (Caps), so a value always exists.</summary>
        internal static int BurstsWithin(int projectiles, int bursts)
        {
            if (projectiles <= 0) return bursts;
            long volleys = bursts > 1 ? bursts : 1;
            if (projectiles * volleys <= BulletsPerTrigger) return bursts;
            int allowed = BulletsPerTrigger / projectiles;
            return allowed < 1 ? 1 : allowed;
        }

        /// <summary>The digest's input: every field and both ends of every
        /// range, every cap, K and the bullet bound, as bytes (UTF-8 names, a 0
        /// separator, little-endian IEEE singles and 32-bit integers), so every
        /// runtime reads the same input.</summary>
        internal static byte[] DigestInput(Range[] ranges, Cap[] caps, int k, int bullets)
        {
            var o = new System.Collections.Generic.List<byte>(2048);
            for (int i = 0; i < ranges.Length; i++)
            {
                o.AddRange(Encoding.UTF8.GetBytes(ranges[i].Field));
                o.Add(0);
                o.AddRange(LittleEndian(BitConverter.GetBytes(ranges[i].Lo)));
                o.AddRange(LittleEndian(BitConverter.GetBytes(ranges[i].Hi)));
            }
            for (int i = 0; i < caps.Length; i++)
            {
                o.AddRange(Encoding.UTF8.GetBytes(caps[i].Field));
                o.Add(0);
                o.AddRange(LittleEndian(BitConverter.GetBytes(caps[i].Max)));
            }
            o.AddRange(LittleEndian(BitConverter.GetBytes(k)));
            o.AddRange(LittleEndian(BitConverter.GetBytes(bullets)));
            return o.ToArray();
        }

        private static byte[] LittleEndian(byte[] b)
        {
            if (!BitConverter.IsLittleEndian) Array.Reverse(b);
            return b;
        }

        /// <summary>The first 8 bytes of the input's SHA-256, as 16 lowercase
        /// hexadecimal characters.</summary>
        internal static string DigestOf(Range[] ranges, Cap[] caps, int k, int bullets)
        {
            byte[] hash;
            using (var sha = SHA256.Create()) hash = sha.ComputeHash(DigestInput(ranges, caps, k, bullets));
            var sb = new StringBuilder(16);
            for (int i = 0; i < 8; i++) sb.Append(hash[i].ToString("x2"));
            return sb.ToString();
        }

        private static string _version;

        /// <summary>The feature's advertised version: the protocol number and
        /// the table's digest. Lane 2 stages it in cr_lim1, and the decision
        /// and the entry check compare it for equality.</summary>
        internal static string Version
        {
            get
            {
                if (_version == null)
                    _version = Protocol.ToString(System.Globalization.CultureInfo.InvariantCulture) + "-"
                               + DigestOf(Ranges, Caps, K, BulletsPerTrigger);
                return _version;
            }
        }
    }
}
