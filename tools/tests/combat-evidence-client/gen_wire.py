"""Combat evidence wire, client half: generate plugin/CombatEvidenceWire.g.cs
from the SERVER branch's COMBAT_WIRE (backend/api/combat_measures.py, read by
path, never written; no bytecode is written beside it), or check that the
checked-in generated file still equals what the server's layout gives.

    python tools/tests/combat-evidence-client/gen_wire.py [--server-root DIR] [--check]

--check exits 1 on any drift (the layout is the server's source of truth).
"""
import os
import sys

sys.dont_write_bytecode = True

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(REPO, "plugin", "CombatEvidenceWire.g.cs")
DEFAULT_SERVER = os.path.join(os.path.dirname(REPO), "scr-wt-combat-evidence-server")
KIND = {"int": 0, "enum": 1, "row": 2, "rows": 3, "hist": 4, "list": 5, "groups": 6, "omit": 7}


def load_server(root):
    api = os.path.join(root, "backend", "api")
    sys.path.insert(0, api)
    import combat_measures  # review_measures registers it once; a second load would duplicate the vocabulary
    return combat_measures


def cs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def longs(xs):
    return "new long[] { " + ", ".join("%dL" % x for x in xs) + " }"


def strs(xs):
    return "new string[] { " + ", ".join(cs_str(x) for x in xs) + " }"


def fields_of(s):
    k = s[0]
    if k == "row":
        return s[1]
    if k == "rows":
        return s[2]
    if k == "list":
        return s[3]
    if k == "groups":
        return s[3]
    return ()


def dbl(v):
    r = repr(float(v))
    return r if ("." in r or "e" in r) else r + ".0"


def render(W):
    spec = W["spec"]
    keys = [k for k, _ in spec]
    lines = []
    a = lines.append
    a("// GENERATED by tools/tests/combat-evidence-client/gen_wire.py from the server's COMBAT_WIRE")
    a("// (backend/api/combat_measures.py). Do not edit by hand: regenerate, and the harness's")
    a("// --check refuses any drift between this file and the server's layout.")
    a("namespace CompetitiveRounds")
    a("{")
    a("    internal static class CombatEvidenceWire")
    a("    {")
    a("        internal const int CONTRACT = %d;" % W["contract"])
    a("        internal const int SCHEMA = %d;" % W["schema"])
    a("        internal static readonly int[] CONSTS_KNOWN = new int[] { %s };" % ", ".join(str(c) for c in W["consts_known"]))
    a("        internal const int RECORD_MAX_BYTES = %d;" % W["record_max_bytes"])
    a("        internal const int SEAT_HOURLY_CAP = %d;" % W["seat_hourly_cap"])
    a("        internal const string SIGN_PREFIX = %s;" % cs_str(W["sign_prefix"]))
    a("        internal const int COLLECTORS = %d;" % W["collectors"])
    a("        internal const int GAP_COUNT = %d;" % W["gap_count"])
    a("        internal const int GROUP_PARTS = %d;" % W["group_parts"])
    a("        internal const long GAP_NONE = %dL;" % W["gap_none"])
    a("        internal const long OWN_SINCE_NONE = %dL;" % W["own_since_none"])
    a("        internal const int RECENT_HITS = %d;" % W["recent_hits"])
    a("        internal const int REGEN_KIND = %d;" % W["regen_kind"])
    a("        internal const int CENTI = %d;" % W["centi"])
    a("        internal const int K_INT = 0, K_ENUM = 1, K_ROW = 2, K_ROWS = 3, K_HIST = 4, K_LIST = 5, K_GROUPS = 6, K_OMIT = 7;")
    a("        internal static readonly string[] KEYS = %s;" % strs(keys))
    a("        internal static readonly int[] KIND = new int[] { %s };" % ", ".join(str(KIND[s[0]]) for _k, s in spec))
    caps, tiers, lo, hi, names, enums, hists = [], [], [], [], [], [], []
    for _k, s in spec:
        kind = s[0]
        cap = s[1] if kind in ("list", "groups", "rows", "hist") else 0
        tier = s[2] if kind in ("list", "groups") else 0
        caps.append(cap)
        tiers.append(tier)
        if kind == "int" or kind == "omit":
            lo.append([s[1]]); hi.append([s[2]]); names.append([])
        elif kind == "hist":
            lo.append([s[2]]); hi.append([s[3]]); names.append([])
        elif kind == "enum":
            lo.append([]); hi.append([]); names.append([])
        else:
            f = fields_of(s)
            lo.append([x[1] for x in f]); hi.append([x[2] for x in f]); names.append([x[0] for x in f])
        enums.append(list(s[1]) if kind == "enum" else [])
    a("        internal static readonly int[] CAP = new int[] { %s };" % ", ".join(str(c) for c in caps))
    a("        internal static readonly int[] TIER = new int[] { %s };" % ", ".join(str(t) for t in tiers))
    a("        internal static readonly long[][] LO = new long[][] {")
    for x in lo:
        a("            %s," % longs(x))
    a("        };")
    a("        internal static readonly long[][] HI = new long[][] {")
    for x in hi:
        a("            %s," % longs(x))
    a("        };")
    a("        internal static readonly string[][] FIELDS = new string[][] {")
    for x in names:
        a("            %s," % strs(x))
    a("        };")
    a("        internal static readonly string[][] ENUMS = new string[][] {")
    for x in enums:
        a("            %s," % strs(x))
    a("        };")
    # groups: per key index (null for non-groups)
    for part, idx, cidx in (("SHOT", 5, 4), ("REGEN", 7, 6)):
        pass
    glines = {"SHOT_CAP": [], "REGEN_CAP": [], "HLO": [], "HHI": [], "HNAMES": [], "SLO": [], "SHI": [], "SNAMES": [],
              "RLO": [], "RHI": [], "RNAMES": []}
    for _k, s in spec:
        if s[0] == "groups":
            glines["SHOT_CAP"].append(str(s[4])); glines["REGEN_CAP"].append(str(s[6]))
            glines["HLO"].append(longs([f[1] for f in s[3]])); glines["HHI"].append(longs([f[2] for f in s[3]]))
            glines["HNAMES"].append(strs([f[0] for f in s[3]]))
            glines["SLO"].append(longs([f[1] for f in s[5]])); glines["SHI"].append(longs([f[2] for f in s[5]]))
            glines["SNAMES"].append(strs([f[0] for f in s[5]]))
            glines["RLO"].append(longs([f[1] for f in s[7]])); glines["RHI"].append(longs([f[2] for f in s[7]]))
            glines["RNAMES"].append(strs([f[0] for f in s[7]]))
        else:
            glines["SHOT_CAP"].append("0"); glines["REGEN_CAP"].append("0")
            for n in ("HLO", "HHI", "SLO", "SHI", "RLO", "RHI", "HNAMES", "SNAMES", "RNAMES"):
                glines[n].append("null")
    a("        internal static readonly int[] SHOT_CAP = new int[] { %s };" % ", ".join(glines["SHOT_CAP"]))
    a("        internal static readonly int[] REGEN_CAP = new int[] { %s };" % ", ".join(glines["REGEN_CAP"]))
    for n, t in (("HLO", "long"), ("HHI", "long"), ("SLO", "long"), ("SHI", "long"), ("RLO", "long"), ("RHI", "long"),
                 ("HNAMES", "string"), ("SNAMES", "string"), ("RNAMES", "string")):
        a("        internal static readonly %s[][] %s = new %s[][] { %s };" % (t, n, t, ", ".join(glines[n])))
    a("        internal static readonly string[][] TIER_ORDER = new string[][] { %s };"
      % ", ".join(strs(t) for t in W["tier_order"]))
    a("        internal static readonly string[][] PROTECT = new string[][] { %s };" % ", ".join(strs(p) for p in W["protect"]))
    for dname in ("caps", "end", "src", "why", "fl", "steer_bits", "cause", "death_cause", "edge", "bounce_target"):
        d = W[dname]
        for name, v in d.items():
            a("        internal const int %s_%s = %d;" % (dname.upper(), name.upper(), v))
    for dname in ("move", "homing", "bounce"):
        for name, v in W[dname].items():
            a("        internal const double %s_%s = %s;" % (dname.upper(), name.upper(), dbl(v)))
    a("        internal static readonly string[][] SECTIONS = new string[][] { %s };"
      % ", ".join(strs([name] + [x for pair in parts for x in pair]) for name, parts in W["sections"]))
    a("    }")
    a("}")
    return "\n".join(lines) + "\n"


def main():
    args = sys.argv[1:]
    root = DEFAULT_SERVER
    if "--server-root" in args:
        root = args[args.index("--server-root") + 1]
    mod = load_server(root)
    text = render(mod.COMBAT_WIRE)
    if "--check" in args:
        cur = open(OUT, "rb").read().decode("utf-8").replace("\r\n", "\n") if os.path.exists(OUT) else ""
        if cur != text:
            print("WIRE DRIFT: plugin/CombatEvidenceWire.g.cs differs from the server's COMBAT_WIRE at", root)
            return 1
        print("wire parity: plugin/CombatEvidenceWire.g.cs equals the server's COMBAT_WIRE (%d keys)" % len(mod.COMBAT_WIRE["spec"]))
        return 0
    with open(OUT, "wb") as f:
        f.write(text.encode("utf-8"))
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
