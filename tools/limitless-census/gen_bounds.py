"""Ask 16(a) D2: the clamp table for limitless games, generated from the game's own values.

census.json, beside this file, holds every shipped card's multipliers and addends for the
clamped fields (neutral values left out), and the player's and the default weapon's base
values, read from the game's assets. This script applies the design's one rule to it and
prints what plugin/LimitlessBounds.cs holds: the 21 ranges, the 8 caps, K, the bullet bound
and the table's digest. That file's numbers come from this output and are never typed;
backend/tests/test_ask16a_lane1_client.py regenerates them and compares.

The rule (ask 16(a) design, section 2): a limitless game keeps each field within what a
normal game already reaches. That is K picks of the strongest shipped card in each
direction, from the player's base, and at least x8 either way. A field that a shipped card
zeroes keeps 0 as its floor; a field whose base is 0 gets [0, 8]. A count is capped at its
base plus K times the largest single-card addend, and at least its base plus K. Bullets per
trigger stay within the most that K picks reach: projectiles x max(1, bursts).

Usage: python gen_bounds.py [--markdown] [census.json] [K]
"""
import hashlib
import json
import os
import struct
import sys

K_DEFAULT = 5


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def lit(x):
    return ("%.9g" % f32(x)) + "f"


def generate(census, k=K_DEFAULT):
    cards = census["cards"]
    ranges = []
    for field, key, base in census["multiplied"]:
        b = float(base)
        fs = [float(c["mult"][key]) for c in cards if key in c["mult"]]
        dn = [x for x in fs if x < 1 - 1e-6]
        up = [x for x in fs if x > 1 + 1e-6]
        if b == 0.0:
            lo, hi = 0.0, 8.0
        else:
            lo = 0.0 if any(x == 0 for x in dn) else b * min(min(dn) ** k if dn else 1.0, 1 / 8)
            hi = b * max(max(up) ** k if up else 1.0, 8.0)
        ranges.append((field, f32(b), f32(lo), f32(hi), min(dn) if dn else None, max(up) if up else None))
    caps = []
    for field, key, base in census["counted"]:
        adds = [float(c["add"][key]) for c in cards if key in c["add"]]
        m = max([a for a in adds if a > 0], default=0)
        caps.append((field, int(base), int(base) + int(max(k * m, k)), m))
    proj = dict((f, b) for f, _, b in census["counted"])["Gun.numberOfProjectiles"]
    p = [float(c["add"]["gun.numberOfProjectiles"]) for c in cards if c["add"].get("gun.numberOfProjectiles")]
    bu = [float(c["add"]["gun.bursts"]) for c in cards if c["add"].get("gun.bursts")]
    bullets = int(max((int(proj) + a * max(p)) * max(1, b * max(bu))
                      for a in range(k + 1) for b in range(k + 1 - a)))
    dig = b""
    for r in ranges:
        dig += r[0].encode("utf-8") + bytes([0]) + struct.pack("<f", r[2]) + struct.pack("<f", r[3])
    for c in caps:
        dig += c[0].encode("utf-8") + bytes([0]) + struct.pack("<i", c[2])
    dig += struct.pack("<i", k) + struct.pack("<i", bullets)
    return {"K": k, "ranges": ranges, "caps": caps, "bullets": bullets,
            "digest": hashlib.sha256(dig).hexdigest()[:16],
            "jumps_added_by": [c["name"] for c in cards if c["add"].get("csm.numberOfJumps")]}


def csharp(t):
    head = "            // generated by tools/limitless-census/gen_bounds.py (K = %d); never edited by hand" % t["K"]
    rs = [head] + ['            new Range("%s", %s, %s, %s),' % (r[0], lit(r[1]), lit(r[2]), lit(r[3])) for r in t["ranges"]]
    cs = [head] + ['            new Cap("%s", %d, %d),' % (c[0], c[1], c[2]) for c in t["caps"]]
    return rs, cs


def markdown(t):
    g = lambda v: "-" if v is None else "%.6g" % v
    out = ["| Field | Base | Strongest card, down / up | Band, K = %d |" % t["K"], "|---|---|---|---|"]
    out += ["| %s | %s | %s / %s | [%s, %s] |" % (r[0], g(r[1]), g(r[4]), g(r[5]), g(r[2]), g(r[3])) for r in t["ranges"]]
    out += ["", "| Count | Base | Largest addend per card | Cap |", "|---|---|---|---|"]
    out += ["| %s | %d | %g | %d |" % (c[0], c[1], c[3], c[2]) for c in t["caps"]]
    out += ["", "Bullets per trigger (projectiles x max(1, bursts)): at most %d. Digest %s." % (t["bullets"], t["digest"])]
    return out


def main(argv):
    md = "--markdown" in argv
    args = [a for a in argv[1:] if a != "--markdown"]
    path = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), "census.json")
    k = int(args[1]) if len(args) > 1 else K_DEFAULT
    with open(path, encoding="utf-8") as fh:
        t = generate(json.load(fh), k)
    if md:
        print("\n".join(markdown(t)))
        return 0
    rs, cs = csharp(t)
    print("\n".join(rs + cs))
    print("// K = %d, bullets = %d, digest = %s, cards adding jumps = %d" % (k, t["bullets"], t["digest"], len(t["jumps_added_by"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
