"""Emit the settings page's generated C# from the committed descriptor table.

    python tools/settings/emit_settings_descriptors.py           write both files
    python tools/settings/emit_settings_descriptors.py --check   exit 1 if either is stale

Item 13 (v1.41.0, the settings page reorganisation). The input is
tools/settings/item13_descriptors.json (schema item13-descriptors/3), the
table the design's generator measured; the frozen authored translation set
is tools/settings/item13_i18n_authored.json. Two outputs, split on purpose:

  plugin/SettingsDescriptors.g.cs        the per-key records and every
      authored display string, each inside its own I18n.Tr literal.
      tools/i18n_extract.py harvests this file, so the authored set enters
      the catalogue key set from here.

  plugin/SettingsDescriptorWriters.g.cs  the writer calls (the per-tab
      reset), the recommended operands and the render expressions. NOT
      harvested: an expression such as I18n.Tr("Full".ToUpperInvariant())
      would otherwise put an identity value into the key set.

Only rows present on the lane ("lane" in present_on) are emitted. Every
authored string is taken from the descriptor table's authored_i18n list and
must be byte-identical to the frozen file's entry of the same (class, key);
a difference refuses to write. Output is ASCII with LF endings: a non-ASCII
character is written as a C# \\uXXXX escape, which the extractor decodes.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DESC = os.path.join(HERE, "item13_descriptors.json")
FROZEN = os.path.join(HERE, "item13_i18n_authored.json")
OUT_DESC = os.path.join(REPO, "plugin", "SettingsDescriptors.g.cs")
OUT_WRITERS = os.path.join(REPO, "plugin", "SettingsDescriptorWriters.g.cs")

HEADER = ("// <auto-generated>\n"
          "// Generated by tools/settings/emit_settings_descriptors.py from\n"
          "// tools/settings/item13_descriptors.json. Do not edit by hand: change the\n"
          "// table and re-run the script (the --check mode fails on a stale file).\n"
          "// </auto-generated>\n")


def cs(s):
    """A C# regular string literal for s, ASCII only."""
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            raise SystemExit("carriage return in an authored string: %r" % s[:60])
        elif ch == "\t":
            raise SystemExit("tab in an authored string: %r" % s[:60])
        elif o < 32:
            raise SystemExit("control character in an authored string: %r" % s[:60])
        elif o > 126:
            if o > 0xFFFF:
                raise SystemExit("astral character in an authored string: %r" % s[:60])
            out.append("\\u%04x" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def callable_name(writer):
    """'NativeUI.SetShowFps(bool)' -> 'NativeUI.SetShowFps'."""
    i = writer.find("(")
    return writer[:i].strip() if i >= 0 else writer.strip()


def load():
    d = json.load(open(DESC, encoding="ascii"))
    if d.get("schema") != "item13-descriptors/3":
        raise SystemExit("unexpected descriptor schema %r" % d.get("schema"))
    frozen = json.load(open(FROZEN, encoding="ascii"))
    if frozen.get("schema") != "item13-i18n-authored/1":
        raise SystemExit("unexpected frozen schema %r" % frozen.get("schema"))
    fz = {(t["class"], t["key"], t["text"]) for t in frozen["terms"]}
    # Round-2 L5: the frozen set is the LANE's authored set - the terms of the
    # rows present on the lane plus the page-wide terms (keys that name no
    # row) - so the table's terms are compared in the same scope. A row the
    # lane does not build (SBugBtn) authors nothing the lane ships.
    desc = d["descriptors"]
    au = {(t["class"], t["key"], t["text"]) for t in d["authored_i18n"]
          if t["key"] not in desc or "lane" in desc[t["key"]]["present_on"]}
    if fz != au:
        raise SystemExit("the descriptor table's authored_i18n differs from the frozen set: "
                         "+%d -%d" % (len(au - fz), len(fz - au)))
    return d


def lane_rows(d):
    rows = []
    for key in sorted(d["descriptors"]):
        r = d["descriptors"][key]
        if "lane" in r["present_on"]:
            rows.append(r)
    return rows


def authored(d, cls, key):
    hits = [t["text"] for t in d["authored_i18n"] if t["class"] == cls and t["key"] == key]
    if len(hits) > 1:
        raise SystemExit("two authored %s entries for %s" % (cls, key))
    return hits[0] if hits else None


def emit_descriptors(d, rows):
    L = [HEADER, "namespace CompetitiveRounds\n{\n"]
    L.append("    /// <summary>One settings row's generated record (item 13).</summary>\n")
    L.append("    internal sealed class SettingsDescriptor\n    {\n")
    L.append("        internal readonly string Key, Kind, Home, RowGroup, HelpTargetId, RecKind, RecValue;\n")
    L.append("        internal readonly bool BulkReset, StoresValue;\n\n")
    L.append("        internal SettingsDescriptor(string key, string kind, string home, bool bulkReset, bool storesValue,\n")
    L.append("                                    string rowGroup, string helpTargetId, string recKind, string recValue)\n")
    L.append("        {\n")
    L.append("            Key = key; Kind = kind; Home = home; BulkReset = bulkReset; StoresValue = storesValue;\n")
    L.append("            RowGroup = rowGroup; HelpTargetId = helpTargetId; RecKind = recKind; RecValue = recValue;\n")
    L.append("        }\n    }\n\n")
    L.append("    /// <summary>The generated descriptor table and its authored display\n")
    L.append("    /// strings. Every string sits inside its own I18n.Tr literal so\n")
    L.append("    /// tools/i18n_extract.py harvests it.</summary>\n")
    L.append("    internal static class SettingsDescriptors\n    {\n")
    L.append("        internal static readonly SettingsDescriptor[] All =\n        {\n")
    for r in rows:
        rec = r.get("recommendation") or {}
        rv = rec.get("value")
        L.append("            new SettingsDescriptor(%s, %s, %s, %s, %s, %s, %s, %s, %s),\n" % (
            cs(r["key"]), cs(r["kind"]), cs(r["home"]),
            "true" if r["bulk_reset"] else "false",
            "true" if r["stores_value"] else "false",
            cs(r["row_group"]), cs(r["help_target_id"]),
            cs(rec.get("kind") or ""), cs(rv) if isinstance(rv, str) else "null"))
    L.append("        };\n\n")
    L.append("        internal static SettingsDescriptor Find(string key)\n        {\n")
    L.append("            foreach (var d in All) if (d.Key == key) return d;\n")
    L.append("            return null;\n        }\n\n")

    def switch(name, cls, doc):
        L.append("        /// <summary>%s</summary>\n" % doc)
        L.append("        internal static string %s(string key)\n        {\n            switch (key)\n            {\n" % name)
        n = 0
        for r in rows:
            t = authored(d, cls, r["key"])
            if t is None:
                continue
            L.append("                case %s: return I18n.Tr(%s);\n" % (cs(r["key"]), cs(t)))
            n += 1
        L.append("                default: return null;\n            }\n        }\n\n")
        return n

    n_reason = switch("ReasonTr", "reason", "The one-line reason under the recommendation strip.")
    n_help = switch("HelpBodyTr", "help_body", "An authored help body (null: the row's own description is the body).")
    n_when = switch("WhenToPressTr", "when_to_press", "When to press an ACTION, DISCLOSURE or DESTRUCTIVE row.")

    # exclusion reasons, grouped by text
    reasons = [t["text"] for t in d["authored_i18n"] if t["class"] == "exclusion_reason"]
    groups = {}
    for r in rows:
        why = r.get("reset_excluded_reason")
        if r["bulk_reset"]:
            if why:
                raise SystemExit("%s is bulk-written and carries an exclusion reason" % r["key"])
            continue
        if not why:
            raise SystemExit("%s is excluded from the reset with no reason" % r["key"])
        if why not in reasons:
            raise SystemExit("%s: exclusion reason is not an authored string: %r" % (r["key"], why[:60]))
        groups.setdefault(why, []).append(r["key"])
    L.append("        /// <summary>Why a row is not written by its tab's reset (shown in the confirm prompt).</summary>\n")
    L.append("        internal static string ExclusionReasonTr(string key)\n        {\n            switch (key)\n            {\n")
    for why in reasons:
        keys = groups.get(why)
        if not keys:
            continue
        for k in keys:
            L.append("                case %s:\n" % cs(k))
        L.append("                    return I18n.Tr(%s);\n" % cs(why))
    L.append("                default: return null;\n            }\n        }\n\n")

    L.append("        /// <summary>A sub-tab's label, by home id.</summary>\n")
    L.append("        internal static string SubTabLabelTr(string home)\n        {\n            switch (home)\n            {\n")
    n_tab = 0
    for t in d["authored_i18n"]:
        if t["class"] == "sub_tab_label":
            L.append("                case %s: return I18n.Tr(%s);\n" % (cs(t["key"]), cs(t["text"])))
            n_tab += 1
    L.append("                default: return home;\n            }\n        }\n    }\n}\n")
    return "".join(L), (n_reason, n_help, n_when, len(groups), n_tab)


def emit_writers(d, rows):
    L = [HEADER, "namespace CompetitiveRounds\n{\n"]
    L.append("    /// <summary>The generated writer side of the settings descriptors\n")
    L.append("    /// (item 13): the per-tab reset's calls, each row's recommended\n")
    L.append("    /// operand, and the render expression of the rows whose recommended\n")
    L.append("    /// word is produced at run time. Deliberately not harvested by\n")
    L.append("    /// tools/i18n_extract.py.</summary>\n")
    L.append("    internal static class SettingsDescriptorWriters\n    {\n")
    L.append("        /// <summary>Run the row's reset call. False when the row is not bulk-written.</summary>\n")
    L.append("        internal static bool InvokeReset(string key)\n        {\n            switch (key)\n            {\n")
    n_reset = 0
    for r in rows:
        if not r["bulk_reset"]:
            continue
        rc = r.get("reset_call") or {}
        if not rc.get("writer"):
            raise SystemExit("%s is bulk-written with no writer" % r["key"])
        L.append("                case %s: %s(%s); return true;\n" % (
            cs(r["key"]), callable_name(rc["writer"]), ", ".join(rc.get("args") or [])))
        n_reset += 1
    L.append("                default: return false;\n            }\n        }\n\n")
    L.append("        /// <summary>The value the row's recommendation stands for, typed for\n")
    L.append("        /// its paint function (null: the row stores no value).</summary>\n")
    L.append("        internal static object RecommendedOperand(string key)\n        {\n            switch (key)\n            {\n")
    n_op = 0
    for r in rows:
        op = r.get("reset_operand") or {}
        expr = op.get("expression")
        if not expr:
            continue
        L.append("                case %s: return %s;\n" % (cs(r["key"]), expr))
        n_op += 1
    L.append("                default: return null;\n            }\n        }\n\n")
    L.append("        /// <summary>The recommended word of a row whose painter renders it at\n")
    L.append("        /// run time (null: the recommendation is the descriptor's painted literal).</summary>\n")
    L.append("        internal static string RenderExpression(string key)\n        {\n            switch (key)\n            {\n")
    n_render = 0
    for r in rows:
        rec = r.get("recommendation") or {}
        expr = (rec.get("render") or {}).get("expression")
        if not expr:
            continue
        L.append("                case %s: return %s;\n" % (cs(r["key"]), expr))
        n_render += 1
    L.append("                default: return null;\n            }\n        }\n    }\n}\n")
    return "".join(L), (n_reset, n_op, n_render)


def main(argv):
    check = "--check" in argv
    d = load()
    rows = lane_rows(d)
    a, na = emit_descriptors(d, rows)
    b, nb = emit_writers(d, rows)
    for text in (a, b):
        if any(ord(c) > 127 for c in text) or "\r" in text:
            raise SystemExit("generated text is not ASCII/LF")
    stale = []
    for path, text in ((OUT_DESC, a), (OUT_WRITERS, b)):
        cur = open(path, "rb").read().decode("ascii") if os.path.exists(path) else None
        if cur != text:
            stale.append(os.path.basename(path))
            if not check:
                with open(path, "w", encoding="ascii", newline="\n") as f:
                    f.write(text)
    print("rows: %d lane (%d bulk-written)" % (len(rows), sum(1 for r in rows if r["bulk_reset"])))
    print("descriptors: reasons %d, help bodies %d, when-to-press %d, exclusion reasons %d, sub-tab labels %d" % na)
    print("writers: reset calls %d, operands %d, render expressions %d" % nb)
    if check:
        print("STALE: " + ", ".join(stale) if stale else "CURRENT: both generated files match the table")
        return 1 if stale else 0
    print("wrote: " + (", ".join(stale) if stale else "nothing (already current)"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
