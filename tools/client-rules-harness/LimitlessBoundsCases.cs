    /// <summary>
    /// Ask 16(a) section 2: LimitlessBounds, executed (suite `limitbounds`).
    /// The pinned table and digest below are the census tool's output
    /// (tools/limitless-census/gen_bounds.py), so the source's table must equal what the tool
    /// measured from the game's assets, field by field and end by end, and a
    /// change to any single bound moves the digest. The clamp and burst rules
    /// run on the real functions and on mutants of them; each mutant must turn
    /// its named cases red (#391). Every case prints its name.
    /// </summary>
    internal static class LimitlessBoundsCases
    {
        internal sealed class Result
        {
            internal int Run, Fail;
            internal readonly StringBuilder Report = new StringBuilder();
        }

        private const string PinnedDigest = "4e4806419fa25528";

        private static readonly LimitlessBounds.Range[] PinnedRanges =
        {
            // generated by tools/limitless-census/gen_bounds.py (K = 5); never edited by hand
            new LimitlessBounds.Range("GunAmmo.reloadTimeMultiplier", 1f, 0.00243000058f, 8f),
            new LimitlessBounds.Range("CharacterStatModifiers.sizeMultiplier", 1f, 0.125f, 8f),
            new LimitlessBounds.Range("CharacterData.maxHealth", 100f, 3.125f, 3200f),
            new LimitlessBounds.Range("CharacterStatModifiers.movementSpeed", 1f, 0.125f, 8f),
            new LimitlessBounds.Range("CharacterStatModifiers.jump", 1f, 0.125f, 8f),
            new LimitlessBounds.Range("Gravity.gravityForce", 1000f, 125f, 8000f),
            new LimitlessBounds.Range("Block.cdMultiplier", 1f, 0.125f, 8f),
            new LimitlessBounds.Range("Gun.damage", 1f, 0.0009765625f, 32f),
            new LimitlessBounds.Range("Gun.chargeDamageMultiplier", 1f, 0.125f, 8f),
            new LimitlessBounds.Range("Gun.knockback", 1f, 0.125f, 97.65625f),
            new LimitlessBounds.Range("Gun.projectileSpeed", 1f, 0.0777600184f, 525.21875f),
            new LimitlessBounds.Range("Gun.projectielSimulatonSpeed", 1f, 0.125f, 32f),
            new LimitlessBounds.Range("Gun.gravity", 1f, 0f, 8f),
            new LimitlessBounds.Range("Gun.multiplySpread", 1f, 0.125f, 8f),
            new LimitlessBounds.Range("Gun.attackSpeed", 0.300000012f, 2.92968783e-09f, 29.2968769f),
            new LimitlessBounds.Range("Gun.bodyRecoil", 0f, 0f, 8f),
            new LimitlessBounds.Range("Gun.speedMOnBounce", 1f, 0.03125f, 8f),
            new LimitlessBounds.Range("Gun.dmgMOnBounce", 1f, 0.125f, 18.8956776f),
            new LimitlessBounds.Range("Gun.bulletDamageMultiplier", 1f, 0.125f, 8f),
            new LimitlessBounds.Range("Gun.damageAfterDistanceMultiplier", 1f, 0.125f, 8f),
            new LimitlessBounds.Range("Gun.timeToReachFullMovementMultiplier", 0f, 0f, 8f),
        };

        private static readonly LimitlessBounds.Cap[] PinnedCaps =
        {
            // generated by tools/limitless-census/gen_bounds.py (K = 5); never edited by hand
            new LimitlessBounds.Cap("Gun.numberOfProjectiles", 1, 21),
            new LimitlessBounds.Cap("Gun.bursts", 0, 15),
            new LimitlessBounds.Cap("Gun.reflects", 0, 25),
            new LimitlessBounds.Cap("Gun.smartBounce", 0, 5),
            new LimitlessBounds.Cap("Gun.randomBounces", 0, 5),
            new LimitlessBounds.Cap("Gun.bulletPortal", 0, 5),
            new LimitlessBounds.Cap("Block.additionalBlocks", 0, 5),
            new LimitlessBounds.Cap("CharacterStatModifiers.respawns", 0, 5),
        };

        private delegate float ClampFn(LimitlessBounds.Range r, float v);
        private delegate int CapFn(LimitlessBounds.Cap c, int v);
        private delegate int BurstsFn(int projectiles, int bursts);

        private static LimitlessBounds.Range RangeOf(string field)
        {
            foreach (var r in LimitlessBounds.Ranges) if (r.Field == field) return r;
            throw new InvalidOperationException("no range " + field);
        }

        private static LimitlessBounds.Cap CapOf(string field)
        {
            foreach (var c in LimitlessBounds.Caps) if (c.Field == field) return c;
            throw new InvalidOperationException("no cap " + field);
        }

        private static List<KeyValuePair<string, bool>> Rules(ClampFn clamp, CapFn cap, BurstsFn bursts)
        {
            var c = new List<KeyValuePair<string, bool>>();
            Action<string, bool> add = (n, ok) => c.Add(new KeyValuePair<string, bool>(n, ok));
            var dmg = RangeOf("Gun.damage");
            var grav = RangeOf("Gun.gravity");
            var proj = CapOf("Gun.numberOfProjectiles");
            add("NaN reads as the floor", clamp(dmg, float.NaN) == dmg.Lo);
            add("+Infinity reads as the ceiling", clamp(dmg, float.PositiveInfinity) == dmg.Hi);
            add("-Infinity reads as the floor", clamp(dmg, float.NegativeInfinity) == dmg.Lo);
            add("below the floor reads as the floor", clamp(dmg, dmg.Lo / 2f) == dmg.Lo);
            add("above the ceiling reads as the ceiling", clamp(dmg, dmg.Hi * 2f) == dmg.Hi);
            add("inside the band is unchanged", clamp(dmg, 1.5f) == 1.5f);
            add("both ends are inside", clamp(dmg, dmg.Lo) == dmg.Lo && clamp(dmg, dmg.Hi) == dmg.Hi);
            add("a zeroed field keeps 0 as its floor", clamp(grav, -1f) == 0f && clamp(grav, 0f) == 0f);
            add("a count above its cap reads as the cap", cap(proj, proj.Max + 1) == proj.Max);
            add("a count at or under its cap is unchanged", cap(proj, proj.Max) == proj.Max && cap(proj, 5) == 5);
            add("bursts give way: 21 projectiles, 15 bursts", bursts(21, 15) == 3);
            add("bursts give way: 10 projectiles, 9 bursts", bursts(10, 9) == 8);
            add("at the bound nothing gives: 9 projectiles, 9 bursts", bursts(9, 9) == 9);
            add("one projectile keeps its bursts", bursts(1, 15) == 15);
            add("no bursts is one volley", bursts(21, 0) == 0);
            return c;
        }

        private static void Check(Result r, string name, bool ok, string got)
        {
            r.Run++;
            if (!ok) r.Fail++;
            r.Report.Append(ok ? "PASS" : "FAIL").Append(" | case=").Append(name)
                    .Append(" | got=").Append(got ?? "(null)").Append('\n');
        }

        private static string F(float v)
        {
            return v.ToString("R", System.Globalization.CultureInfo.InvariantCulture);
        }

        private static void Control(Result r, string mutant, List<KeyValuePair<string, bool>> cases, params string[] mustFail)
        {
            var failed = new HashSet<string>();
            foreach (var kv in cases)
                if (!kv.Value) failed.Add(kv.Key);
            bool ok = true;
            foreach (var name in mustFail)
                if (!failed.Contains(name)) ok = false;
            Check(r, "mutant (" + mutant + ") is caught by its named cases", ok,
                  failed.Count == 0 ? "no case failed" : string.Join("; ", new List<string>(failed).ToArray()));
        }

        internal static Result Run()
        {
            var r = new Result();
            var ranges = LimitlessBounds.Ranges;
            var caps = LimitlessBounds.Caps;
            Check(r, "the table has the tool's 21 ranges and 8 caps",
                  ranges.Length == PinnedRanges.Length && caps.Length == PinnedCaps.Length
                  && PinnedRanges.Length == 21 && PinnedCaps.Length == 8,
                  ranges.Length + " ranges, " + caps.Length + " caps");
            for (int i = 0; i < PinnedRanges.Length; i++)
            {
                var p = PinnedRanges[i];
                bool ok = i < ranges.Length;
                var s = ok ? ranges[i] : p;
                ok = ok && s.Field == p.Field && s.Base == p.Base && s.Lo == p.Lo && s.Hi == p.Hi;
                Check(r, "range " + p.Field + " is the census tool's", ok,
                      s.Field + " base " + F(s.Base) + " [" + F(s.Lo) + ", " + F(s.Hi) + "]");
            }
            for (int i = 0; i < PinnedCaps.Length; i++)
            {
                var p = PinnedCaps[i];
                bool ok = i < caps.Length;
                var s = ok ? caps[i] : p;
                ok = ok && s.Field == p.Field && s.Base == p.Base && s.Max == p.Max;
                Check(r, "cap " + p.Field + " is the census tool's", ok, s.Field + " base " + s.Base + " cap " + s.Max);
            }
            bool inside = true;
            foreach (var x in ranges) if (!(x.Lo <= x.Base && x.Base <= x.Hi)) inside = false;
            foreach (var x in caps) if (!(x.Base <= x.Max)) inside = false;
            Check(r, "every base lies inside its band", inside, inside ? "yes" : "no");
            string digest = LimitlessBounds.DigestOf(ranges, caps, LimitlessBounds.K, LimitlessBounds.BulletsPerTrigger);
            Check(r, "the digest is the census tool's", digest == PinnedDigest, digest);
            Check(r, "the version is the protocol and the digest",
                  LimitlessBounds.Version == LimitlessBounds.Protocol + "-" + PinnedDigest, LimitlessBounds.Version);
            int still = 0, tried = 0;
            for (int i = 0; i < ranges.Length; i++)
                for (int end = 0; end < 2; end++)
                {
                    var rs = (LimitlessBounds.Range[])ranges.Clone();
                    var x = rs[i];
                    float lo = x.Lo, hi = x.Hi;
                    if (end == 0) lo = lo == 0f ? 1e-30f : lo * 1.5f; else hi = hi * 1.5f;
                    rs[i] = new LimitlessBounds.Range(x.Field, x.Base, lo, hi);
                    tried++;
                    if (LimitlessBounds.DigestOf(rs, caps, LimitlessBounds.K, LimitlessBounds.BulletsPerTrigger) == PinnedDigest) still++;
                }
            for (int i = 0; i < caps.Length; i++)
            {
                var cs = (LimitlessBounds.Cap[])caps.Clone();
                cs[i] = new LimitlessBounds.Cap(cs[i].Field, cs[i].Base, cs[i].Max + 1);
                tried++;
                if (LimitlessBounds.DigestOf(ranges, cs, LimitlessBounds.K, LimitlessBounds.BulletsPerTrigger) == PinnedDigest) still++;
            }
            bool kMoves = LimitlessBounds.DigestOf(ranges, caps, LimitlessBounds.K + 1, LimitlessBounds.BulletsPerTrigger) != PinnedDigest
                          && LimitlessBounds.DigestOf(ranges, caps, LimitlessBounds.K, LimitlessBounds.BulletsPerTrigger + 1) != PinnedDigest;
            Check(r, "every single-bound change, K and the bullet bound move the digest",
                  still == 0 && tried == 2 * ranges.Length + caps.Length && kMoves,
                  tried + " bound changes, " + still + " left the digest unchanged; K and bullets " + (kMoves ? "move it" : "do not"));

            foreach (var kv in Rules(LimitlessBounds.Clamp, LimitlessBounds.Clamp, LimitlessBounds.BurstsWithin))
                Check(r, "real: " + kv.Key, kv.Value, kv.Value ? "holds" : "broken");
            Control(r, "NaN passes through", Rules((x, v) => float.IsNaN(v) ? v : LimitlessBounds.Clamp(x, v),
                    LimitlessBounds.Clamp, LimitlessBounds.BurstsWithin), "NaN reads as the floor");
            Control(r, "no ceiling", Rules((x, v) => float.IsNaN(v) || v < x.Lo ? LimitlessBounds.Clamp(x, v) : v,
                    LimitlessBounds.Clamp, LimitlessBounds.BurstsWithin),
                    "+Infinity reads as the ceiling", "above the ceiling reads as the ceiling");
            Control(r, "no floor", Rules((x, v) => float.IsNaN(v) || v > x.Hi ? LimitlessBounds.Clamp(x, v) : v,
                    LimitlessBounds.Clamp, LimitlessBounds.BurstsWithin),
                    "-Infinity reads as the floor", "below the floor reads as the floor");
            Control(r, "no cap", Rules(LimitlessBounds.Clamp, (x, v) => v, LimitlessBounds.BurstsWithin),
                    "a count above its cap reads as the cap");
            Control(r, "bursts never give way", Rules(LimitlessBounds.Clamp, LimitlessBounds.Clamp, (p, b) => b),
                    "bursts give way: 21 projectiles, 15 bursts", "bursts give way: 10 projectiles, 9 bursts");
            return r;
        }
    }
