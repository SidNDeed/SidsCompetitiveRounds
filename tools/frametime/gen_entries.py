#!/usr/bin/env python3
"""gen_entries.py: write plugin/FtEntries.cs from gate_specs/entries.py (ids in table order, one registration each),
and, for every patched entry (shape not "call"), the patch class whose body holds the entry's census gate
`FtCensus.Skip(FtE.<id>)`: found by reading plugin/*.cs, the nearest class header above the one gate line, which
must be exactly one line in all the sources (FtCalib calibrates each patched entry with that class's own patch
methods; round-1 MEDIUM, FtCalib.cs:163). Usage: python -I -B gen_entries.py <worktree>"""
import glob
import os
import re
import runpy
import sys

w = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
rows = runpy.run_path(os.path.join(here, "gate_specs", "entries.py"))["ENTRIES"]
consts = [c for c, n, k, s in rows]
if len(set(consts)) != len(consts):
    sys.exit("REFUSED: duplicate const in entries.py")

src = {}
for p in sorted(glob.glob(os.path.join(w, "plugin", "*.cs"))):
    if os.path.basename(p) == "FtEntries.cs":
        continue
    src[os.path.basename(p)] = open(p, encoding="utf-8-sig").read().replace("\r\n", "\n").split("\n")
CLASS = re.compile(r"^\s*(?:(?:internal|public|private|static|sealed)\s+)*class\s+(\w+)")
patch_type = {}
for c, n, k, s in rows:
    if s == "call":
        continue
    if s != c:
        sys.exit("REFUSED: patched entry %s has shape %r; a patched entry is its own shape" % (c, s))
    gate = "FtCensus.Skip(FtE.%s)" % c
    hits = []
    for f, lines in src.items():
        for i, ln in enumerate(lines):
            if gate in ln:
                cls = next((m.group(1) for m in (CLASS.match(lines[j]) for j in range(i, -1, -1)) if m), None)
                hits.append((f, i + 1, cls))
    if len(hits) != 1 or hits[0][2] is None:
        sys.exit("REFUSED: %s's gate line found %d times (%s)" % (c, len(hits), hits))
    patch_type[c] = hits[0][2]

out = ["#if SCR_FRAMETIME",
       "namespace CompetitiveRounds",
       "{",
       "    /// <summary>FrameTime M3 census ids (METHOD-V4.md 3.12; VR5), generated by",
       "    /// tools/frametime/gen_entries.py from tools/frametime/gate_specs/entries.py, which says",
       "    /// which entries are listed and why: the outermost live entries of INVENTORY.md, each with",
       "    /// its component and shape (a patched entry is its own shape). RegisterAll runs once at clock",
       "    /// install, so every census line lists every gated entry, reached or not; it logs the count,",
       "    /// any id left unregistered and any registered twice. PatchType names each patched entry's",
       "    /// patch class (the class holding its census gate), which FtCalib calibrates.</summary>",
       "    internal static class FtE",
       "    {"]
for i, (c, n, k, s) in enumerate(rows):
    out.append("        internal const int %s = %d;" % (c, i))
out += ["",
        "        internal const int Count = %d;" % len(rows),
        "",
        "        private static bool _done;",
        "",
        "        internal static void RegisterAll()",
        "        {",
        "            if (_done) return;",
        "            _done = true;"]
for c, n, k, s in rows:
    out.append('            FtCensus.Set(%s, "%s", FtSpan.%s, "%s");' % (c, n.replace(" ", ":"), k, s))
out += ["            int missing = 0;",
        "            for (int i = 0; i < Count; i++) if (FtCensus.Names[i] == null) missing++;",
        '            Plugin.Log.LogInfo("[FRAME-TIME] census registered=" + FtCensus.Count + " expected=" + Count + " missing=" + missing',
        '                + " duplicates=" + FtCensus.Duplicates);',
        "        }",
        "",
        "        /// <summary>A patched entry's patch class; null for a direct-call entry.</summary>",
        "        internal static System.Type PatchType(int id)",
        "        {",
        "            switch (id)",
        "            {"]
for c, n, k, s in rows:
    if c in patch_type:
        out.append("                case %s: return typeof(%s);" % (c, patch_type[c]))
out += ["                default: return null;",
        "            }",
        "        }",
        "    }",
        "}",
        "#endif",
        ""]
open(os.path.join(w, "plugin", "FtEntries.cs"), "w", encoding="utf-8", newline="").write("\n".join(out))
print("gen_entries: %d entries, %d patch classes" % (len(rows), len(patch_type)))
