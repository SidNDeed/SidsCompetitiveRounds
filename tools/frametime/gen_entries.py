#!/usr/bin/env python3
"""gen_entries.py: write plugin/FtEntries.cs from gate_specs/entries.py (ids in table order, one registration each).
Usage: python -I -B gen_entries.py <worktree>"""
import os
import runpy
import sys

w = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
rows = runpy.run_path(os.path.join(here, "gate_specs", "entries.py"))["ENTRIES"]
consts = [c for c, n, k, s in rows]
if len(set(consts)) != len(consts):
    sys.exit("REFUSED: duplicate const in entries.py")
out = ["#if SCR_FRAMETIME",
       "namespace CompetitiveRounds",
       "{",
       "    /// <summary>FrameTime M3 census ids (METHOD-V4.md 3.12; VR5), generated by",
       "    /// tools/frametime/gen_entries.py from tools/frametime/gate_specs/entries.py, which says",
       "    /// which entries are listed and why: the outermost live entries of INVENTORY.md, each with",
       "    /// its component and patch shape. RegisterAll runs once at clock install, so every census",
       "    /// line lists every gated entry, reached or not; it logs the count, any id left",
       "    /// unregistered and any registered twice.</summary>",
       "    internal static class FtE",
       "    {"]
for i, (c, n, k, s) in enumerate(rows):
    out.append("        internal const int %s = %d;" % (c, i))
out += ["",
        "        internal const int Count = %d;" % len(rows),
        "",
        "        private static bool _done;",
        "",
        "        internal static void RegisterAll()",
        "        {",
        "            if (_done) return;",
        "            _done = true;"]
for c, n, k, s in rows:
    out.append('            FtCensus.Set(%s, "%s", FtSpan.%s, "%s");' % (c, n.replace(" ", ":"), k, s))
out += ["            int missing = 0;",
        "            for (int i = 0; i < Count; i++) if (FtCensus.Names[i] == null) missing++;",
        '            Plugin.Log.LogInfo("[FRAME-TIME] census registered=" + FtCensus.Count + " expected=" + Count + " missing=" + missing',
        '                + " duplicates=" + FtCensus.Duplicates);',
        "        }",
        "    }",
        "}",
        "#endif",
        ""]
open(os.path.join(w, "plugin", "FtEntries.cs"), "w", encoding="utf-8", newline="").write("\n".join(out))
print("gen_entries: %d entries" % len(rows))
